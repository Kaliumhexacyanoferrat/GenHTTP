using System.Security.Cryptography.X509Certificates;

using GenHTTP.Api.Content;
using GenHTTP.Api.Content.Authentication;
using GenHTTP.Api.Content.Documentation.Security;
using GenHTTP.Api.Protocol;

using GenHTTP.Modules.Authentication.Documentation;

namespace GenHTTP.Modules.Authentication.ClientCertificate;

/// <summary>
/// Configures a concern that authenticates clients by the certificate they presented
/// during the TLS handshake.
/// </summary>
/// <remarks>
/// Client certificates are not documented as a security scheme by default, as the OpenAPI
/// specification generated by the framework (version 3.0) does not support them. To document
/// the mechanism, pass a scheme to <see cref="Documentation(SecurityScheme)" />, which is also
/// required for a description passed to <see cref="Documentation(string)" /> to be shown.
/// </remarks>
public sealed class ClientCertificateAuthenticationBuilder : IAuthenticationBuilder<ClientCertificateAuthenticationBuilder>
{
    private readonly ClientCertificateAuthenticationOptions _options = new();

    private readonly SchemeDocumentation _documentation = new();

    /// <summary>
    /// Sets a delegate that will be invoked to check whether the client
    /// is allowed to access the inner content. If the delegate returns false,
    /// the client will receive a 403 forbidden response.
    /// </summary>
    /// <param name="authorizer">The delegate to be invoked for authorization</param>
    public ClientCertificateAuthenticationBuilder Authorization(Func<IRequest, X509Certificate?, ValueTask<bool>> authorizer)
    {
        _options.Authorizer = authorizer;
        return this;
    }

    /// <summary>
    /// Sets a delegate that will be invoked to set the user record on the request, allowing
    /// inner handlers to consume this information as needed.
    /// </summary>
    /// <param name="userMapping">The delegate to determine the user</param>
    public ClientCertificateAuthenticationBuilder UserMapping(Func<IRequest, X509Certificate?, ValueTask<IUser?>> userMapping)
    {
        _options.UserMapping = userMapping;
        return this;
    }

    public ClientCertificateAuthenticationBuilder Documentation(string description)
    {
        _documentation.Description = description;
        return this;
    }

    public ClientCertificateAuthenticationBuilder Documentation(SecurityScheme scheme)
    {
        _documentation.Scheme = scheme;
        return this;
    }

    public IConcern Build(IHandler content)
    {
        return new ClientCertificateAuthenticationConcern(content, _options, _documentation.ResolveOptional(null));
    }

}
